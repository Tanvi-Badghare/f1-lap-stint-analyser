"""SYNTHETIC demo data so the website can be tried without internet. NOT real F1 data."""
from __future__ import annotations

from types import SimpleNamespace

import numpy as np
import pandas as pd

from .config import AnalysisConfig

DRIVERS = ["AAA", "BBB", "CCC", "DDD", "EEE", "FFF", "GGG", "HHH"]
SYNTH_NOTE = "SYNTHETIC demo data generated by f1analyser.demo - not real F1 data."


def make_laps(n_laps=57, pit_laps=(24,), seed=1, gap_b=0.30, deg=0.05, fuel=0.03, spread=0.7):
    """AAA is faster than BBB by gap_b s/lap; true in-stint slope is deg - fuel."""
    rng = np.random.default_rng(seed)
    rows = []
    for k, drv in enumerate(DRIVERS):
        k_eff = 0 if drv in ("AAA", "BBB") else k
        base = 90.0 + spread * k_eff + (gap_b if drv == "BBB" else 0.0)
        stint, age, comp, t_end = 1, 1, "MEDIUM", 0.0
        for lap in range(1, n_laps + 1):
            pit_in = pit_out = pd.NaT
            if lap in pit_laps:
                pit_in = pd.Timedelta(seconds=t_end)
            if lap - 1 in pit_laps:
                stint, age, comp = stint + 1, 1, "HARD"
                pit_out = pd.Timedelta(seconds=t_end)
            lt = base + deg * age - fuel * lap + rng.normal(0, 0.12)
            if lap in pit_laps or lap - 1 in pit_laps:
                lt += 20
            t_end += lt
            S = lambda frac, extra=0.0: pd.Timedelta(seconds=float(lt * frac + extra))
            rows.append(dict(
                Driver=drv, LapNumber=lap, LapTime=pd.Timedelta(seconds=float(lt)),
                Sector1Time=S(0.30, 0.05 if drv == "BBB" else 0), Sector2Time=S(0.40, 0.20 if drv == "BBB" else 0),
                Sector3Time=S(0.30, 0.05 if drv == "BBB" else 0), Stint=stint, Compound=comp, TyreLife=float(age),
                TrackStatus="1", IsAccurate=True, Deleted=False, PitInTime=pit_in, PitOutTime=pit_out,
                Time=pd.Timedelta(seconds=float(t_end))))
            age += 1
    return pd.DataFrame(rows)


def make_telemetry(lap_time=90.0, length=5000.0, hz=5, slower_zone=None):
    """One synthetic lap with two slow corners (at 1250 m and 3750 m). slower_zone=(d0, d1, seconds_lost)."""
    n = int(lap_time * hz)
    s = np.linspace(0, 1, n)
    dist = s * length
    speed = 220 + 80 * np.cos(2 * np.pi * 2 * s)
    brake = (np.gradient(speed) < -0.3) & (speed < 260)
    throttle = np.where(np.gradient(speed) >= 0, 100.0, 0.0)
    t = np.linspace(0, lap_time, n)
    if slower_zone:
        d0, d1, extra = slower_zone
        t = t + extra * ((dist - d0) / (d1 - d0)).clip(0, 1)
    return pd.DataFrame({
        "Distance": dist, "T": t, "Time": pd.to_timedelta(t, unit="s"), "Speed": speed, "Throttle": throttle,
        "Brake": brake, "nGear": np.clip((speed // 40).astype(int), 1, 8),
        "X": 1000 * np.cos(2 * np.pi * s), "Y": 600 * np.sin(2 * np.pi * s)})


def demo_result() -> dict:
    from .service import compute_all

    cfg = AnalysisConfig(year=2000, gp="Synthetic", session="R", driver_a="AAA", driver_b="BBB", n_bootstrap=1500)
    session = SimpleNamespace(laps=make_laps())
    tel_fn = lambda s, drv, lap: make_telemetry(90.0, slower_zone=(2000, 2500, 0.3) if drv == "BBB" else None)
    meta = dict(event="Synthetic demo GP", session_name="Race", session_date="n/a", fastf1_version="n/a",
                weather=None, teams={}, synthetic=True, data_source=SYNTH_NOTE)
    corners = pd.DataFrame({"Number": [1, 2], "Letter": ["", ""], "Distance": [1250.0, 3750.0]})
    return compute_all(cfg, session=session, tel_fn=tel_fn, meta=meta, corners_df=corners)
